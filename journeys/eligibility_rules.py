def _rule(questions, name=None, cat=None, not_name=None):
    """قاعدة تطابق اسم الخدمة و/أو تصنيفها؛ إذا حُدد الاثنان يجب أن يتطابقا معًا."""
    if not (name or cat):
        raise ValueError(f"قاعدة الأهلية يجب أن تحتوي على name أو cat، الأسئلة: {questions}")
    compile_ = lambda p: re.compile(normalize_arabic(p)) if p else None
    return {"questions": questions, "name": compile_(name), "cat": compile_(cat), "not_name": compile_(not_name)}


