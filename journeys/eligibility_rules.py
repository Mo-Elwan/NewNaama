def _unique(ids):
    return list(dict.fromkeys(ids))


def _matches(rule, name_n, cat_n):
    if rule["name"] and not rule["name"].search(name_n):
        return False
    if rule["cat"] and not rule["cat"].search(cat_n):
        return False
    return not (rule["not_name"] and rule["not_name"].search(name_n))


def service_questions(name, category):
    """أسئلة الخدمة حسب مسماها وتصنيفها، أو سؤال المستندات العام إذا لم تطابق أي قاعدة."""
    name_n, cat_n = normalize_arabic(name), normalize_arabic(category)
    matched = [q for rule in SERVICE_RULES if _matches(rule, name_n, cat_n) for q in rule["questions"]]
    return _unique(matched) or list(FALLBACK_QUESTIONS)


def action_questions(stage, operation):
    """أسئلة إضافية خاصة بالإجراء الفرعي (مثل اشتراط ترخيص مبدئي قبل الإنشائي)."""
    return _unique(
        q for (rule_stage, rule_operation), questions in ACTION_RULES
        if rule_operation == operation and rule_stage in (None, stage)
        for q in questions
    )


def question_label(question_id):
    """نص السؤال مع الأنواع المخصص لها، لعرضه في ملف المراجعة."""
    question = QUESTIONS[question_id]
    types = [TAXONOMY[t]["label"] for t in question.get("for_types", [])]
    return question["text"] + (f" [{'، '.join(types)} فقط]" if types else "")


def validate_questions():
    """يتأكد أن كل سؤال مستخدم معرّف وكل سؤال معرّف مستخدم، لاكتشاف الأخطاء الإملائية مبكرًا."""
    used = set(FALLBACK_QUESTIONS)
    used.update(q for rule in SERVICE_RULES for q in rule["questions"])
    used.update(q for _, questions in ACTION_RULES for q in questions)
    missing = used - QUESTIONS.keys()
    if missing:
        raise ValueError(f"أسئلة أهلية غير معرّفة في QUESTIONS: {sorted(missing)}")
    unused = QUESTIONS.keys() - used
    if unused:
        raise ValueError(f"أسئلة أهلية معرّفة لكنها غير مربوطة بأي قاعدة: {sorted(unused)}")
    for question_id, question in QUESTIONS.items():
        unknown_types = set(question.get("for_types", [])) - TAXONOMY.keys()
        if unknown_types:
            raise ValueError(f"السؤال {question_id} يشير لأنواع مستفيد غير معرّفة: {sorted(unknown_types)}")
